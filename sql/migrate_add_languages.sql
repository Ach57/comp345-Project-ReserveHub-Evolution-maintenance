CREATE TABLE IF NOT EXISTS `languages` (
  `code`       VARCHAR(10)  NOT NULL,
  `name`       VARCHAR(100) NOT NULL,
  `is_active`  TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (`code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `translation_pages` (
  `page_key`   VARCHAR(50) NOT NULL,
  PRIMARY KEY (`page_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `translations` (
  `id`                INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `language_code`     VARCHAR(10)  NOT NULL,
  `page_key`          VARCHAR(50)  NOT NULL,
  `translation_key`   VARCHAR(255) NOT NULL,
  `translation_value` TEXT         NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_translation` (`language_code`, `page_key`, `translation_key`),
  FOREIGN KEY (`language_code`) REFERENCES `languages`(`code`)   ON UPDATE CASCADE ON DELETE CASCADE,
  FOREIGN KEY (`page_key`)      REFERENCES `translation_pages`(`page_key`) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

